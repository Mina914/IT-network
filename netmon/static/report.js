(() => {
  "use strict";
  const $ = (id) => document.getElementById(id);
  const esc = (s) => String(s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
  const dur = (s) => { s = Math.round(s); if (!s) return "0"; const d = Math.floor(s / 86400), h = Math.floor(s % 86400 / 3600), m = Math.floor(s % 3600 / 60);
    return d ? `${d}d ${h}h` : h ? `${h}h ${m}m` : m ? `${m}m ${s % 60}s` : `${s}s`; };
  const pct = (v) => `<span class="${v >= 99.9 ? "good" : v >= 99 ? "warn" : "bad"}">${v === 100 ? "100" : Math.min(v, 99.999).toFixed(3)}%</span>`;
  const dt = (t) => new Date(t * 1000).toLocaleString([], { year: "numeric", month: "short", day: "numeric", hour: "2-digit", minute: "2-digit" });
  const fmtBps = (m) => m >= 1000 ? `${m / 1000}G` : `${m}M`;
  const WARN = { cpu: "High CPU", mem: "High memory", temp: "Temperature", fan: "Fan", psu: "Power supply", poe: "PoE budget", util: "High utilisation", err: "Port errors" };
  let range = "week";

  async function load() {
    $("out").innerHTML = `<p class="muted">Loading…</p>`;
    const r = await fetch(`/api/report?range=${range}`);
    if (r.status === 401) { location.href = "/login"; return; }
    const d = await r.json();
    const s = d.summary;
    const warn = Object.entries(s.warnings);
    $("out").innerHTML = `
      <h1>Network availability report</h1>
      <p class="period">${dt(d.start)} – ${dt(d.end)} · ${s.switches} switches · ${s.links} uplinks</p>
      <div class="kpis">
        <div class="kpi"><div class="k">Worst availability</div><div class="v">${pct(s.worst_availability)}</div></div>
        <div class="kpi"><div class="k">Uplink outages</div><div class="v">${s.link_outages}</div></div>
        <div class="kpi"><div class="k">Switch outages</div><div class="v">${s.switch_outages}</div></div>
        <div class="kpi"><div class="k">Time with any problem</div><div class="v">${dur(s.time_with_any_problem_s)}</div></div>
      </div>
      ${warn.length ? `<p class="note">Warnings in this period: ${warn.map(([k, n]) => `${esc(WARN[k] || k)} ×${n}`).join(" · ")}</p>` : ""}

      <h2>Uplinks</h2>
      <div class="table-wrap"><table><thead><tr><th>Link</th><th class="num">Outages</th><th class="num">Downtime</th><th class="num">Longest</th><th class="num">Availability</th></tr></thead>
      <tbody>${d.links.map((l) => `<tr><td>${esc(l.link)}</td><td class="num">${l.outages}</td><td class="num">${dur(l.downtime_s)}</td><td class="num">${dur(l.longest_s)}</td><td class="num">${pct(l.availability)}</td></tr>`).join("")}</tbody></table></div>
      <p class="note">An outage on either end of a link counts once. A switch that stops answering counts as an outage of all its links.</p>

      <h2>Switches</h2>
      <div class="table-wrap"><table><thead><tr><th>Switch</th><th>Floor</th><th class="num">Unreachable</th><th class="num">Downtime</th><th class="num">Port alarms</th><th class="num">Availability</th></tr></thead>
      <tbody>${d.devices.map((x) => `<tr><td><b>${esc(x.device)}</b> <span class="muted">${esc(x.host)}</span></td><td>${x.role === "core" ? "Core" : x.floor}</td><td class="num">${x.outages}</td><td class="num">${dur(x.downtime_s)}</td><td class="num">${x.port_alarms}</td><td class="num">${pct(x.availability)}</td></tr>`).join("")}</tbody></table></div>

      <h2>Busiest ports (peak)</h2>
      ${d.utilization.length ? `<div class="table-wrap"><table><thead><tr><th>Switch</th><th>Port</th><th class="num">Speed</th><th class="num">Peak</th><th class="num">Average</th></tr></thead>
      <tbody>${d.utilization.map((u) => `<tr><td>${esc(u.device)}</td><td>${esc(u.port)}</td><td class="num">${fmtBps(u.speed)}</td><td class="num ${u.peak_pct >= 80 ? "bad" : ""}">${u.peak_pct.toFixed(1)}%</td><td class="num">${u.avg_pct.toFixed(1)}%</td></tr>`).join("")}</tbody></table></div>` : `<p class="muted">No traffic history yet.</p>`}

      <h2>Ports with the most errors</h2>
      ${d.errors.length ? `<div class="table-wrap"><table><thead><tr><th>Switch</th><th>Port</th><th>Description</th><th class="num">Errors since boot</th></tr></thead>
      <tbody>${d.errors.map((e) => `<tr><td>${esc(e.device)}</td><td>${esc(e.port)}</td><td>${esc(e.description || "—")}</td><td class="num">${e.errors.toLocaleString()}</td></tr>`).join("")}</tbody></table></div>
      <p class="note">Steadily growing errors usually mean a bad cable, patch cord or SFP.</p>` : `<p class="muted">No port errors.</p>`}
      <p class="note">Generated by NetMon on ${dt(d.generated)}.</p>`;
  }
  $("seg").addEventListener("click", (e) => {
    const b = e.target.closest("button"); if (!b) return;
    range = b.dataset.r;
    $("seg").querySelectorAll("button").forEach((x) => x.classList.toggle("active", x === b));
    load();
  });
  $("print").addEventListener("click", () => window.print());
  load();
})();
